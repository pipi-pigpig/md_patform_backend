# DMC（碳酸二甲酯）分子生成
# ============================================================

def generate_dmc():
    """
    生成 DMC 分子的 3D 坐标

    分子结构:
        O1
        ||
        C1 — O2 — C2(H1,H2,H3)
         |
         O3 — C3(H4,H5,H6)

    几何参数:
        - C1=O1: 1.20 Å (沿 +z 方向)
        - C1-O2: 1.36 Å (在 xy 平面内)
        - C1-O3: 1.36 Å (在 xy 平面内)
        - O2-C2: 1.43 Å
        - O3-C3: 1.43 Å
        - O=C-O 角: 120°
        - C-O-C 角: 116°
    """
    # 键长
    r_CO_double = 1.20   # C=O 双键
    r_CO_single = 1.36   # C-O 单键
    r_OC = 1.43          # O-CH3 键
    r_CH = 1.09          # C-H 键

    # C1 在原点
    c1 = np.array([0.0, 0.0, 0.0])
    # O1 沿 +z 方向（C=O 双键）
    o1 = c1 + np.array([0.0, 0.0, r_CO_double])
    # O2 在 xy 平面，与 O1 夹角 120°（即与 +z 方向夹角 120°，在 xy 平面）
    # O2 = 1.36 * (sin(120°), 0, cos(120°)) = 1.36 * (0.866, 0, -0.5)
    o2 = c1 + r_CO_single * np.array([math.sin(math.radians(120)), 0.0, math.cos(math.radians(120))])
    # O3 在 xy 平面另一侧，与 O1 夹角 120°，与 O2 夹角 120°
    # O3 = 1.36 * (sin(120°)*cos(120°), sin(120°)*sin(120°), cos(120°))
    # 简化：O3 在 xy 平面内与 O2 关于 z 轴对称的另一侧
    o3 = c1 + r_CO_single * np.array([math.sin(math.radians(120)) * math.cos(math.radians(120)),
                                       math.sin(math.radians(120)) * math.sin(math.radians(120)),
                                       math.cos(math.radians(120))])
    # 实际上更简单：O2 在 xz 平面，O3 在 xz 平面另一侧（关于 z 轴对称）
    # 让我重新计算：C1 在原点，O1 沿 +z，O2 和 O3 在与 O1 夹角 120° 的方向上
    # O2 方向: (sin(120°), 0, cos(120°)) = (0.866, 0, -0.5)
    # O3 方向: (-sin(120°), 0, cos(120°)) 不对，这样 O2-O3 角度只有 60°
    # 正确: O2 和 O3 在与 O1 夹角 120° 的圆锥上，且 O2-O3 之间夹角也是 120°
    # 让 O2 在 xz 平面正侧: (sin(120°), 0, cos(120°))
    # O3 在 xz 平面负侧: (-sin(120°), 0, cos(120°)) — 这样 O2-O3 夹角是 2*arcsin(sin(120°)) = ?
    # 实际上，三个氧原子在以 C1 为中心、与 C1-O1 轴夹角 120° 的圆锥上，间隔 120°
    # O1 = (0, 0, 1.20)
    # O2 = 1.36 * (sin(120°)*cos(0), sin(120°)*sin(0), cos(120°)) = 1.36*(0.866, 0, -0.5)
    # O3 = 1.36 * (sin(120°)*cos(120°), sin(120°)*sin(120°), cos(120°)) = 1.36*(-0.433, 0.75, -0.5)
    # 验证 O2-O3 距离: sqrt((0.866+0.433)^2 + (0-0.75)^2 + 0) = sqrt(1.687 + 0.5625) = sqrt(2.25) = 1.5
    # 实际期望: O2-O3 = 2*1.36*sin(120°/2) = 2*1.36*sin(60°) = 2*1.36*0.866 = 2.356
    # 不对，O2-C1-O3 角度应该是 120°，O2-O3 = 2*1.36*sin(60°) = 2.356
    # 我的计算结果 1.5 不对，让我重新算
    # O2 = 1.36 * (0.866, 0, -0.5) = (1.178, 0, -0.68)
    # O3 = 1.36 * (-0.433, 0.75, -0.5) = (-0.589, 1.02, -0.68)
    # O2-O3 = (1.767, -1.02, 0), |O2-O3| = sqrt(3.122 + 1.04) = sqrt(4.162) = 2.04
    # 还是不对，应该是 2.356

    # 让我用更直接的方法：三个氧原子在 xy 平面内，间隔 120°，C1 在原点
    # O1 沿 +x 方向: (1.20, 0, 0)
    # O2 在 xy 平面，与 O1 夹角 120°: (1.36*cos(120°), 1.36*sin(120°), 0) = (-0.68, 1.177, 0)
    # O3 在 xy 平面，与 O1 夹角 240°（即 -120°）: (1.36*cos(240°), 1.36*sin(240°), 0) = (-0.68, -1.177, 0)
    # 这样 O2-O3 = 2*1.177 = 2.354，符合 2*1.36*sin(60°) = 2.356 ✓
    o1 = np.array([r_CO_double, 0.0, 0.0])
    o2 = np.array([r_CO_single * math.cos(math.radians(120)),
                   r_CO_single * math.sin(math.radians(120)),
                   0.0])
    o3 = np.array([r_CO_single * math.cos(math.radians(240)),
                   r_CO_single * math.sin(math.radians(240)),
                   0.0])

    # C2: 从 O2 延伸 O-CH3 键，C-O-C 角度 116°
    # C1-O2 方向: (o2 - c1) = o2，归一化
    c1_o2_dir = normalize(o2 - c1)
    # C2 在 O2 的延伸方向上，但与 C1-O2 方向夹角为 180°-116° = 64°（向外）
    # 让 C2 在 xy 平面外侧（远离 C1 方向）
    # O2 处的 C-O-C 角度: C1-O2-C2 = 116°，所以 O2-C2 方向与 O2-C1 方向夹角 116°
    # O2-C1 方向 = -c1_o2_dir
    # 让 C2 在 xy 平面内，O2-C2 方向 = 旋转 (-c1_o2_dir) 绕 z 轴旋转 (180°-116°)=64°
    # 即 O2-C2 方向与 O2-C1 方向（指向 C1）夹角 116°
    # 简化：C2 = O2 + 1.43 * (从 C1->O2 方向绕 z 轴旋转 -64°)
    # 这样 C2 在 O2 外侧，C1-O2-C2 角度为 180°-64°=116°
    o2_c2_dir = rotate_vector(c1_o2_dir, np.array([0, 0, 1]), -64.0)
    c2 = o2 + r_OC * o2_c2_dir

    # C3: 对称地，从 O3 延伸
    c1_o3_dir = normalize(o3 - c1)
    # O3 在下方，C3 应该在 O3 外侧（绕 z 轴旋转 +64°，因为 O3 在第三象限）
    o3_c3_dir = rotate_vector(c1_o3_dir, np.array([0, 0, 1]), 64.0)
    c3 = o3 + r_OC * o3_c3_dir

    # C2 的三个氢原子（四面体几何）
    h1, h2, h3 = build_tetrahedral_hydrogens(c2, o2, r_CH)
    # C3 的三个氢原子
    h4, h5, h6 = build_tetrahedral_hydrogens(c3, o3, r_CH)

    atoms = [
        ('C1', 'C', c1[0], c1[1], c1[2]),
        ('O1', 'O', o1[0], o1[1], o1[2]),
        ('O2', 'O', o2[0], o2[1], o2[2]),
        ('O3', 'O', o3[0], o3[1], o3[2]),
        ('C2', 'C', c2[0], c2[1], c2[2]),
        ('C3', 'C', c3[0], c3[1], c3[2]),
        ('H1', 'H', h1[0], h1[1], h1[2]),
        ('H2', 'H', h2[0], h2[1], h2[2]),
        ('H3', 'H', h3[0], h3[1], h3[2]),
        ('H4', 'H', h4[0], h4[1], h4[2]),
        ('H5', 'H', h5[0], h5[1], h5[2]),
        ('H6', 'H', h6[0], h6[1], h6[2]),
    ]

    bonds = [
        (1, 2),   # C1-O1
        (1, 3),   # C1-O2
        (1, 4),   # C1-O3
        (3, 5),   # O2-C2
        (4, 6),   # O3-C3
        (5, 7), (5, 8), (5, 9),     # C2-H1, C2-H2, C2-H3
        (6, 10), (6, 11), (6, 12),  # C3-H4, C3-H5, C3-H6
    ]

    return atoms, bonds


