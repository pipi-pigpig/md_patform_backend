"""
fix_molecule_pdb.py - 修复 DMC.pdb 和 EC.pdb 的 3D 坐标

功能：
    1. 生成 DMC（碳酸二甲酯）分子的正确 3D 几何构型
    2. 生成 EC（碳酸乙烯酯）分子的正确 3D 几何构型
    3. 确保所有原子间距离合理，避免 Packmol 初始构型重叠

分子几何参数（标准实验值）：
    键长：
        - C=O (羰基双键): 1.20 Å
        - C-O (酯键): 1.36 Å
        - O-CH3 (醚键): 1.43 Å
        - C-H: 1.09 Å
        - C-C (EC 环): 1.54 Å
    键角：
        - O=C-O (sp2): 120°
        - C-O-C (醚): 116°
        - O-C-H (sp3): 109.5°
        - H-C-H (sp3): 109.5°

作者: Electrolyte MD Platform
版本: 1.0
"""

import os
import math
import numpy as np


# ============================================================
# 向量运算工具函数
# ============================================================

def normalize(v):
    """归一化向量"""
    norm = np.linalg.norm(v)
    if norm < 1e-10:
        return v
    return v / norm


def rotate_vector(v, axis, angle_deg):
    """
    绕指定轴旋转向量
    使用 Rodrigues 旋转公式

    参数:
        v: 待旋转向量
        axis: 旋转轴（会自动归一化）
        angle_deg: 旋转角度（度）
    """
    axis = normalize(axis)
    angle = math.radians(angle_deg)
    cos_a = math.cos(angle)
    sin_a = math.sin(angle)
    # Rodrigues 旋转公式: v*cos + (k×v)*sin + k*(k·v)*(1-cos)
    return v * cos_a + np.cross(axis, v) * sin_a + axis * np.dot(axis, v) * (1 - cos_a)


def build_tetrahedral_hydrogens(center, bonded_atom, bond_length=1.09):
    """
    构建甲基（CH3）的三个氢原子，使用标准四面体几何

    参数:
        center: 甲基碳原子坐标 (numpy array)
        bonded_atom: 与甲基碳成键的原子坐标（用于确定方向）
        bond_length: C-H 键长

    返回:
        三个氢原子的坐标列表
    """
    # 主键方向（从 bonded_atom 指向 center）
    main_bond = normalize(center - bonded_atom)
    # 找一个与主键方向不平行的向量作为辅助轴
    if abs(main_bond[2]) < 0.9:
        helper = np.array([0.0, 0.0, 1.0])
    else:
        helper = np.array([1.0, 0.0, 0.0])
    # 构造垂直于主键的平面内的两个正交向量
    perp1 = normalize(np.cross(main_bond, helper))
    perp2 = normalize(np.cross(main_bond, perp1))

    # 四面体角: H-C-键 角度为 109.5°
    # main_bond 是从 bonded_atom 指向 center 的方向（即从 O 指向 C）
    # H 应该在 center 的另一侧（远离 bonded_atom），即沿 +main_bond 方向
    # H 方向与 main_bond 方向夹角为 180°-109.5° = 70.5°
    # 在垂直平面内三个 H 间隔 120°
    tilt_angle = 180.0 - 109.5  # 70.5°
    h_atoms = []
    for i in range(3):
        phi = 120.0 * i  # 0°, 120°, 240°
        # 在 perp1-perp2 平面内旋转，H 沿 +main_bond 方向（远离成键原子）
        direction = math.cos(math.radians(tilt_angle)) * main_bond + \
                    math.sin(math.radians(tilt_angle)) * \
                    (math.cos(math.radians(phi)) * perp1 + math.sin(math.radians(phi)) * perp2)
        direction = normalize(direction)
        h_pos = center + bond_length * direction
        h_atoms.append(h_pos)
    return h_atoms


# ============================================================
# PDB 文件写入
# ============================================================

def write_pdb(filename, header, atoms, bonds):
    """
    写入 PDB 文件

    参数:
        filename: 输出文件路径
        header: PDB 头信息
        atoms: 原子列表，每个元素为 (name, element, x, y, z)
        bonds: 键列表，每个元素为 (atom1_idx, atom2_idx)（1-based）
    """
    with open(filename, 'w') as f:
        f.write(f"HEADER    {header}\n")
        f.write(f"COMPND    {header}\n")
        f.write("AUTHOR    GENERATED BY MD PLATFORM\n")
        for i, (name, element, x, y, z) in enumerate(atoms, 1):
            # PDB 格式: ATOM  序号 原子名 残基名 残基序号 x y z 占据率 温度因子 元素
            f.write(f"ATOM  {i:5d}  {name:<3s} {header:<3s}     1    "
                    f"{x:8.3f}{y:8.3f}{z:8.3f}  1.00  0.00          {element:>2s}\n")
        for b1, b2 in bonds:
            f.write(f"CONECT {b1:5d}{b2:5d}\n")
        f.write("END\n")
    print(f"已生成: {filename} ({len(atoms)} 个原子, {len(bonds)} 个键)")


