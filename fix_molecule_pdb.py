# EC（碳酸乙烯酯）分子生成
# ============================================================

def generate_ec():
    """
    生成 EC 分子的 3D 坐标

    分子结构（五元环）:
        O1
        ||
        C1 — O2 — C2 — C3 — O3 — C1 (闭环)

    几何参数:
        - C1=O1: 1.20 Å (羰基双键)
        - C1-O2: 1.36 Å
        - C1-O3: 1.36 Å
        - O2-C2: 1.43 Å
        - O3-C3: 1.43 Å
        - C2-C3: 1.54 Å
        - C-H: 1.09 Å (4 个氢，每个 CH2 两个)

    五元环角度: 内角约 108°（接近正五边形）
    """
    # 键长
    r_CO_double = 1.20   # C=O 双键
    r_CO_single = 1.36   # C-O 单键
    r_OC = 1.43          # O-CH2 键
    r_CC = 1.54          # C-C 键
    r_CH = 1.09          # C-H 键

    # 构建五元环 C1-O2-C2-C3-O3-C1
    # 让五元环在 xy 平面，C1 在底部，O1 沿 -y 方向（向下）
    # 五元环顶点（正五边形，中心在原点，半径 r）
    # 内角 108°，但 EC 五元环不是正五边形，简化为近似正五边形
    # 五元环半径: 由键长决定
    # 正五边形边长 a 与外接圆半径 R 的关系: a = 2*R*sin(36°), R = a/(2*sin(36°))
    # 平均键长 ≈ (1.36+1.43+1.54+1.43+1.36)/5 = 1.424
    avg_bond = 1.424
    R = avg_bond / (2 * math.sin(math.radians(36)))

    # 五元环顶点（C1, O2, C2, C3, O3）按逆时针排列
    # 让 C1 在底部（角度 -90°，即 -y 方向）
    # 顶点角度: -90°, -90°+72°=-18°, -90°+144°=54°, -90°+216°=126°, -90°+288°=198°
    angles = [-90 + 72 * i for i in range(5)]
    ring_atoms = [np.array([R * math.cos(math.radians(a)),
                            R * math.sin(math.radians(a)),
                            0.0]) for a in angles]

    # 按顺序: C1, O2, C2, C3, O3
    c1, o2, c2, c3, o3 = ring_atoms

    # O1: C=O 双键，从 C1 向外（远离环中心）方向
    # C1 在 -y 方向，所以 O1 沿 -y 方向延伸
    c1_to_center = normalize(np.array([0, 0, 0]) - c1)  # 从 C1 指向环中心
    o1 = c1 + r_CO_double * (-c1_to_center)  # O1 沿 C1 远离中心方向

    # 调整环内键长（正五边形边长可能不等于实际键长）
    # 简化：保持正五边形几何，键长近似即可（Packmol 只需要初始构型）

    # C2 的两个氢原子（CH2，sp3 杂化）
    # C2 连接 O2 和 C3，H 在环平面外
    # C2-H 方向: 垂直于 O2-C2-C3 平面，向 +z 和 -z 方向
    c2_normal = np.array([0, 0, 1.0])  # 环平面法向
    # C2-H 方向在环平面外侧 + 法向方向
    # 简化：两个 H 对称分布在环平面上下
    # C2 中心方向（远离环中心）
    c2_outward = normalize(c2 - np.array([0, 0, 0]))
    # H 方向 = outward 倾斜 + 法向
    tilt = math.cos(math.radians(60))  # 60° 倾斜
    h_dir1 = normalize(c2_outward * tilt + c2_normal * math.sin(math.radians(60)))
    h_dir2 = normalize(c2_outward * tilt - c2_normal * math.sin(math.radians(60)))
    h1 = c2 + r_CH * h_dir1
    h2 = c2 + r_CH * h_dir2

    # C3 的两个氢原子（对称）
    c3_outward = normalize(c3 - np.array([0, 0, 0]))
    h_dir3 = normalize(c3_outward * tilt + c2_normal * math.sin(math.radians(60)))
    h_dir4 = normalize(c3_outward * tilt - c2_normal * math.sin(math.radians(60)))
    h3 = c3 + r_CH * h_dir3
    h4 = c3 + r_CH * h_dir4

    atoms = [
        ('C1', 'C', c1[0], c1[1], c1[2]),
        ('O1', 'O', o1[0], o1[1], o1[2]),
        ('O2', 'O', o2[0], o2[1], o2[2]),
        ('O3', 'O', o3[0], o3[1], o3[2]),
        ('C2', 'C', c2[0], c2[1], c2[2]),
        ('C3', 'C', c3[0], c3[1], c3[2]),
        ('H1', 'H', h1[0], h1[1], h1[2]),
        ('H2', 'H', h2[0], h2[1], h2[2]),
        ('H3', 'H', h3[0], h3[1], h3[2]),
        ('H4', 'H', h4[0], h4[1], h4[2]),
    ]

    bonds = [
        (1, 2),   # C1-O1
        (1, 3),   # C1-O2
        (1, 4),   # C1-O3
        (3, 5),   # O2-C2
        (4, 6),   # O3-C3
        (5, 6),   # C2-C3
        (5, 7), (5, 8),   # C2-H1, C2-H2
        (6, 9), (6, 10),  # C3-H3, C3-H4
    ]

    return atoms, bonds


