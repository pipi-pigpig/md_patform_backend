# 验证原子距离
# ============================================================

def check_min_distance(atoms, name):
    """检查原子间最小距离，确保没有重叠"""
    min_dist = float('inf')
    min_pair = None
    coords = np.array([[a[2], a[3], a[4]] for a in atoms])
    for i in range(len(coords)):
        for j in range(i + 1, len(coords)):
            d = np.linalg.norm(coords[i] - coords[j])
            if d < min_dist:
                min_dist = d
                min_pair = (atoms[i][0], atoms[j][0])
    print(f"  {name}: 最小原子间距 = {min_dist:.3f} Å ({min_pair[0]}-{min_pair[1]})")
    if min_dist < 1.0:
        print(f"  警告: {name} 存在过近的原子对（< 1.0 Å）")
    else:
        print(f"  ✓ {name} 原子间距合理")
    return min_dist


